#!/usr/bin/env python3
"""AI Digital Locker - Demo Traffic Simulator.

Generates realistic synthetic traffic against the FastAPI backend using only
the public authenticated API. All accounts, documents, and activity are
synthetic demo data. Never use against production environments.

WARNING: This script creates real accounts and documents in the backend.
Only run against a dedicated demo/staging environment.
"""

from __future__ import annotations

import argparse
import hashlib
import mimetypes
import os
import random
import secrets
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import httpx

DEFAULT_BASE_URL = "http://127.0.0.1:8000"
DEFAULT_USER_COUNT = 8
DEFAULT_DURATION_SECONDS = 300
DEFAULT_MAX_UPLOADS_PER_USER = 5

# Only localhost addresses are allowed without --allow-remote
LOCALHOST_PATTERNS = ("127.0.0.1", "localhost", "localhost.localdomain")

DEMO_EMAIL_DOMAIN = "demo.ai-digital-locker.test"
DEMO_EMAIL_PREFIX = "demo-drill"

# Synthetic document content templates
DOCUMENT_FILENAMES = [
    "demo-internship-certificate.pdf",
    "demo-project-report.pdf",
    "demo-meeting-notes.txt",
    "demo-budget-spreadsheet.csv",
    "demo-travel-receipt.pdf",
    "demo-conference-schedule.pdf",
    "demo-resume.pdf",
    "demo-tax-form.pdf",
    "demo-medical-record.pdf",
    "demo-training-manual.txt",
]

DOCUMENT_CONTENT_TEMPLATES: dict[str, bytes] = {
    ".pdf": (
        b"AI Digital Locker - Demo Document\n"
        b"This is synthetic test content generated by the demo traffic simulator.\n"
        b"Document: {filename}\n"
        b"Generated: {timestamp}\n"
    ),
    ".txt": (
        b"Demo document content.\n"
        b"This file was generated by the AI Digital Locker demo traffic "
        b"simulator for demonstration purposes.\n"
        b"Filename: {filename}\n"
        b"Generated: {timestamp}\n"
    ),
    ".csv": (
        b"Date,Item,Amount\n"
        b"2026-10-01,Demo Item 1,100.00\n"
        b"2026-10-02,Demo Item 2,200.00\n"
    ),
    ".json": (
        b'{\n'
        b'  "demo": true,\n'
        b'  "purpose": "testing",\n'
        b'  "generated_by": "ai-digital-locker-demo",\n'
        b'  "filename": "{filename}"\n'
        b"}\n"
    ),
}


class DemoAccount:
    """Represents a demo user account with its session token."""

    def __init__(self, email: str, password: str, user_id: str) -> None:
        self.email = email
        self.password = password
        self.user_id = user_id
        self.token: str | None = None
        self.document_ids: list[str] = []

    @property
    def auth_headers(self) -> dict[str, str]:
        return {"Authorization": f"Bearer {self.token}"} if self.token else {}


class DemoDriver:
    """Orchestrates the demo traffic simulation."""

    def __init__(
        self,
        base_url: str,
        seed: int | None = None,
        user_count: int = DEFAULT_USER_COUNT,
        duration_seconds: int = DEFAULT_DURATION_SECONDS,
        max_uploads_per_user: int = DEFAULT_MAX_UPLOADS_PER_USER,
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self.rng = random.Random(seed)
        self.user_count = user_count
        self.duration_seconds = duration_seconds
        self.max_uploads_per_user = max_uploads_per_user
        self.accounts: list[DemoAccount] = []
        self.http_client = httpx.Client(base_url=base_url, timeout=30.0)

    def _generate_document_content(self, filename: str) -> bytes:
        """Generate synthetic document content based on file extension."""
        ext = Path(filename).suffix.lower()
        base = (
            b"AI Digital Locker Demo Document\n"
            b"Filename: " + filename.encode("utf-8") + b"\n"
            b"Generated: "
            + datetime.now(timezone.utc).isoformat().encode("utf-8")
            + b"\n"
            b"Demo Account: Synthetic test data\n\n"
            b"This document was created by the AI Digital Locker demo traffic "
            b"simulator. It contains synthetic content for demonstration "
            b"purposes only.\n\n"
        )

        if ext == ".csv":
            base += b"Header1,Header2,Header3\n"
            base += b"Value1,Value2,Value3\n"
            base += b"Value4,Value5,Value6\n"
        elif ext == ".json":
            base += b'{\n'
            base += b'  "demo": true,\n'
            base += b'  "purpose": "testing",\n'
            base += b'  "generated_by": "ai-digital-locker-demo",\n'
            base += b'  "filename": "'
            base += filename.encode("utf-8") + b'",\n'
            base += b"}\n"

        return base

    def _create_account(self) -> DemoAccount | None:
        """Register a new demo account via the public API."""
        email = f"{DEMO_EMAIL_PREFIX}-{self.rng.randint(100000, 999999)}@{DEMO_EMAIL_DOMAIN}"
        password = secrets.token_urlsafe(24)

        try:
            resp = self.http_client.post(
                "/auth/register",
                json={"email": email, "password": password},
                timeout=10.0,
            )
        except httpx.RequestError:
            return None

        if resp.status_code != 201:
            return None

        body = resp.json()
        account = DemoAccount(
            email=email,
            password=password,
            user_id=str(body["id"]),
        )
        self.accounts.append(account)
        return account

    def _login_account(self, account: DemoAccount) -> bool:
        """Log in and obtain session token."""
        try:
            resp = self.http_client.post(
                "/auth/login",
                json={"email": account.email, "password": account.password},
                timeout=10.0,
            )
        except httpx.RequestError:
            return False

        if resp.status_code != 200:
            return False

        body = resp.json()
        account.token = body["access_token"]
        return True

    def _upload_document(self, account: DemoAccount) -> str | None:
        """Upload a synthetic document as the given account."""
        filename = self.rng.choice(DOCUMENT_FILENAMES)
        content = self._generate_document_content(filename)
        content_type = mimetypes.guess_type(filename)[0] or "application/octet-stream"

        try:
            resp = self.http_client.post(
                "/documents",
                headers=account.auth_headers,
                files={"file": (filename, content, content_type)},
                timeout=30.0,
            )
        except httpx.RequestError:
            return None

        if resp.status_code != 201:
            return None

        body = resp.json()
        document_id = str(body["id"])
        account.document_ids.append(document_id)
        return document_id

    def _list_documents(self, account: DemoAccount) -> None:
        """List documents for the given account."""
        try:
            self.http_client.get(
                "/documents",
                headers=account.auth_headers,
                timeout=10.0,
            )
        except httpx.RequestError:
            pass

    def _download_document(self, account: DemoAccount, document_id: str) -> None:
        """Download a document owned by the given account."""
        try:
            resp = self.http_client.get(
                f"/documents/{document_id}",
                headers=account.auth_headers,
                timeout=30.0,
            )
        except httpx.RequestError:
            return
        _ = resp.content

    def _rename_document(self, account: DemoAccount, document_id: str) -> None:
        """Rename a document owned by the given account."""
        new_name = f"renamed-document-{self.rng.randint(1000, 9999)}.txt"
        try:
            self.http_client.patch(
                f"/documents/{document_id}",
                headers=account.auth_headers,
                json={"filename": new_name},
                timeout=10.0,
            )
        except httpx.RequestError:
            pass

    def _delete_document(self, account: DemoAccount, document_id: str) -> None:
        """Delete a document owned by the given account."""
        try:
            resp = self.http_client.delete(
                f"/documents/{document_id}",
                headers=account.auth_headers,
                timeout=10.0,
            )
        except httpx.RequestError:
            return
        if resp.status_code == 204:
            if document_id in account.document_ids:
                account.document_ids.remove(document_id)

    def _random_delay(self, min_seconds: float = 0.5, max_seconds: float = 3.0) -> None:
        """Sleep for a random duration."""
        time.sleep(self.rng.uniform(min_seconds, max_seconds))

    def run_user_session(self, account: DemoAccount) -> None:
        """Run a complete demo session for a single user."""
        # Login
        if not self._login_account(account):
            return

        # Upload 1-3 documents
        num_uploads = self.rng.randint(1, min(3, self.max_uploads_per_user))
        for _ in range(num_uploads):
            self._upload_document(account)
            self._random_delay(0.5, 2.0)

        # List documents
        self._list_documents(account)
        self._random_delay(0.5, 1.5)

        # Download one document if we have any
        if account.document_ids:
            doc_id = self.rng.choice(account.document_ids)
            self._download_document(account, doc_id)
            self._random_delay(0.5, 2.0)

        # Rename one document if we have any
        if account.document_ids:
            doc_id = self.rng.choice(account.document_ids)
            self._rename_document(account, doc_id)
            self._random_delay(0.5, 1.5)

        # Delete one document if we have more than one
        if len(account.document_ids) > 1:
            doc_id = self.rng.choice(account.document_ids)
            self._delete_document(account, doc_id)
            self._random_delay(0.5, 1.5)

    def run(self) -> None:
        """Run the full demo simulation."""
        print("=" * 60)
        print("AI Digital Locker - Demo Traffic Simulator")
        print("=" * 60)
        print(f"Target:      {self.base_url}")
        print(f"Users:       {self.user_count}")
        print(f"Duration:    {self.duration_seconds}s")
        print(f"Max uploads per user: {self.max_uploads_per_user}")
        print(f"Seed:        {self.rng.random()}")
        print("=" * 60)

        # Register and login all users
        print("\n[Phase 1] Registering and logging in users...")
        for i in range(self.user_count):
            account = self._create_account()
            if account is None:
                print(f"  [WARN] Failed to create account {i + 1}/{self.user_count}")
                continue
            if not self._login_account(account):
                print(f"  [WARN] Failed to login account {i + 1}/{self.user_count}")
                continue
            print(f"  [OK] Created and logged in user {i + 1}/{self.user_count}: {account.email}")
            self._random_delay(0.2, 0.8)

        if not self.accounts:
            print("\n[ERROR] No accounts were created. Aborting.")
            return

        # Run user sessions
        print(f"\n[Phase 2] Running user sessions ({len(self.accounts)} users)...")
        for i, account in enumerate(self.accounts):
            print(f"  [User {i + 1}/{len(self.accounts)}] {account.email}")
            self.run_user_session(account)

        total_docs = sum(len(a.document_ids) for a in self.accounts)
        print(f"\n[Phase 3] Demo session complete.")
        print(f"Total documents created: {total_docs}")

    def cleanup(self) -> None:
        """Delete all documents created by demo accounts."""
        print("\n[Cleanup] Deleting demo documents...")
        total_deleted = 0
        for account in self.accounts:
            doc_ids = list(account.document_ids)
            for doc_id in doc_ids:
                self._delete_document(account, doc_id)
                total_deleted += 1
            print(f"  Cleaned up {len(doc_ids)} document(s) for {account.email}")
        print(f"Total documents deleted: {total_deleted}")


def _is_localhost(url: str) -> bool:
    """Check if the URL points to a localhost address."""
    lower = url.lower()
    return any(pattern in lower for pattern in LOCALHOST_PATTERNS)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=(
            "AI Digital Locker - Demo Traffic Simulator\n"
            "Generates realistic synthetic traffic against the FastAPI backend "
            "using only the public authenticated API. "
            "WARNING: This creates real accounts and documents. "
            "Only run against a dedicated demo/staging environment."
        ),
    )
    parser.add_argument(
        "--base-url",
        default=DEFAULT_BASE_URL,
        help=f"Backend base URL (default: {DEFAULT_BASE_URL})",
    )
    parser.add_argument(
        "--user-count",
        type=int,
        default=DEFAULT_USER_COUNT,
        help=f"Number of demo user accounts to create (default: {DEFAULT_USER_COUNT})",
    )
    parser.add_argument(
        "--duration-seconds",
        type=int,
        default=DEFAULT_DURATION_SECONDS,
        help=f"Approximate duration in seconds (default: {DEFAULT_DURATION_SECONDS})",
    )
    parser.add_argument(
        "--max-uploads-per-user",
        type=int,
        default=DEFAULT_MAX_UPLOADS_PER_USER,
        help=f"Max uploads per user (default: {DEFAULT_MAX_UPLOADS_PER_USER})",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=None,
        help="Random seed for reproducible demo runs",
    )
    parser.add_argument(
        "--run",
        action="store_true",
        help="Actually run the demo (required to make any changes)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show what would be done without making any network requests",
    )
    parser.add_argument(
        "--cleanup",
        action="store_true",
        help="Delete all documents created by this simulator (requires --run)",
    )
    parser.add_argument(
        "--allow-remote",
        action="store_true",
        help="Allow running against non-localhost URLs (dangerous)",
    )

    args = parser.parse_args(argv)

    # Validate base URL
    base_url = args.base_url
    if not _is_localhost(base_url) and not args.allow_remote:
        print(
            "ERROR: Refusing to run against non-localhost URL "
            f"{base_url}. Use --allow-remote to override.",
            file=sys.stderr,
        )
        return 2

    # Validate mode
    if args.cleanup and not args.run:
        print(
            "ERROR: --cleanup requires --run",
            file=sys.stderr,
        )
        return 2

    if args.dry_run and args.run:
        print(
            "ERROR: --dry-run and --run are mutually exclusive",
            file=sys.stderr,
        )
        return 2

    if not args.run and not args.dry_run:
        print(
            "ERROR: Must specify either --run or --dry-run",
            file=sys.stderr,
        )
        print("  Run with --dry-run to see what would happen")
        print("  Run with --run to actually execute the demo")
        return 2

    # Validate user count
    if args.user_count < 1 or args.user_count > 20:
        print("ERROR: User count must be between 1 and 20", file=sys.stderr)
        return 2

    print("=" * 60)
    print("AI Digital Locker - Demo Traffic Simulator")
    print("=" * 60)
    print(f"Target:      {base_url}")
    print(f"Users:       {args.user_count}")
    print(f"Duration:    {args.duration_seconds}s")
    print(f"Max uploads per user: {args.max_uploads_per_user}")
    print(f"Seed:        {args.seed if args.seed is not None else 'random'}")
    print(f"Mode:        {'DRY RUN' if args.dry_run else 'LIVE'}")
    print("=" * 60)

    driver = DemoDriver(
        base_url=base_url,
        seed=args.seed,
        user_count=args.user_count,
        duration_seconds=args.duration_seconds,
        max_uploads_per_user=args.max_uploads_per_user,
    )

    if args.dry_run:
        print("\n[Dry-run mode] Would create accounts, upload documents, "
              "and interact with the backend via the public API.")
        print("  No network requests will be made.")
        return 0

    if args.cleanup:
        driver.cleanup()
        return 0

    driver.run()

    print("\n[Demo complete]")
    return 0


if __name__ == "__main__":
    sys.exit(main())